"""Offline, transactional SQLite snapshot import. Never rewrites the source database.

This is migration tooling, not the application's PostgreSQL runtime adapter.
Use PLANTSENSE_MIGRATION_DSN for credentials; never put a DSN in command arguments.
"""

import argparse
import hashlib
import json
import os
import re
import sqlite3
import sys
from contextlib import closing, contextmanager
from pathlib import Path
from tempfile import TemporaryDirectory

from app.cases.schema import SQL as CASE_SCHEMA
from app.persistence.workspace_schema import SCHEMA

ROWID_TABLES = {"plant_areas", "plant_assets", "plant_dependencies", "telemetry_records"}


def canonical():
    """Introspect only trusted, repository-owned DDL, never submitted database SQL."""
    db = sqlite3.connect(":memory:")
    db.execute("CREATE TABLE sessions (id TEXT PRIMARY KEY, owner TEXT, data TEXT)")
    db.execute("CREATE TABLE budgets (day TEXT PRIMARY KEY, calls INTEGER)")
    db.executescript(SCHEMA)
    db.executescript(CASE_SCHEMA)
    return db


def definitions(db):
    return {
        name: statement
        for name, statement in db.execute(
            "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
        )
    }


def table_order(tables):
    result = []
    pending = dict(tables)
    while pending:
        ready = [
            name
            for name, statement in pending.items()
            if set(re.findall(r"REFERENCES\s+(\w+)", statement)) <= set(result) | {name}
        ]
        if not ready:
            raise ValueError("Unsupported cyclic or missing schema dependency")
        for name in sorted(ready):
            result.append(name)
            del pending[name]
    return result


def postgres_ddl():
    """Port the fixed schema, retaining constraints and original immutable triggers."""
    with closing(canonical()) as db:
        tables = definitions(db)
        output = []
        for name in table_order(tables):
            statement = tables[name]
            if name in ROWID_TABLES:
                end = statement.rfind(")")
                statement = (
                    statement[:end]
                    + ", rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE"
                    + statement[end:]
                )
            statement = statement.replace(
                "INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            )
            # SQLite REAL is IEEE 754 double precision; PostgreSQL REAL is single precision.
            statement = re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)
            output.append(statement)
        output.extend(
            statement
            for (statement,) in db.execute(
                "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name"
            )
        )
        output.append(
            "CREATE FUNCTION reject_immutable_mutation() RETURNS trigger LANGUAGE plpgsql "
            "SET search_path = pg_catalog AS $$ BEGIN "
            "RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE='23514'; END $$"
        )
        for (statement,) in db.execute("SELECT sql FROM sqlite_master WHERE type='trigger' ORDER BY name"):
            match = re.fullmatch(
                r"CREATE TRIGGER (\w+) BEFORE (UPDATE|DELETE) ON (\w+)\s+"
                r"BEGIN SELECT RAISE\(ABORT,'([^']+)'\); END",
                statement.strip(),
            )
            if not match:
                raise ValueError("Unsupported trusted trigger definition")
            name, operation, table, message = match.groups()
            output.append(
                f"CREATE TRIGGER {name} BEFORE {operation} ON {table} FOR EACH ROW "
                f"EXECUTE FUNCTION reject_immutable_mutation('{message}')"
            )
        return output


@contextmanager
def snapshot(path):
    """SQLite backup includes WAL changes and provides a consistent, read-only copy."""
    source = Path(path).resolve(strict=True)
    with TemporaryDirectory(prefix="plantsense-migration-") as directory:
        target = Path(directory) / "snapshot.db"
        with closing(sqlite3.connect(source.as_uri() + "?mode=ro", uri=True)) as original:
            with closing(sqlite3.connect(target)) as copy:
                original.backup(copy)
        db = sqlite3.connect(target.as_uri() + "?mode=ro", uri=True)
        try:
            if db.execute("PRAGMA integrity_check").fetchone() != ("ok",):
                raise ValueError("Source integrity check failed")
            if db.execute("PRAGMA foreign_key_check").fetchone():
                raise ValueError("Source has foreign key violations")
            yield db
        finally:
            db.close()


def validate_source(source):
    with closing(canonical()) as expected:
        if set(definitions(source)) != set(definitions(expected)):
            raise ValueError("Source tables differ from the current reviewed schema")
        for name in definitions(expected):
            if (
                source.execute(f'PRAGMA table_info("{name}")').fetchall()
                != expected.execute(f'PRAGMA table_info("{name}")').fetchall()
            ):
                raise ValueError("Source columns differ from the current reviewed schema")
    if {r[0] for r in source.execute("SELECT version FROM workspace_migrations")} != set(range(1, 8)):
        raise ValueError("Source must have completed migrations 1 through 7")
    if source.execute("SELECT 1 FROM issue_jobs WHERE state IN ('queued','running') LIMIT 1").fetchone():
        raise ValueError("Drain case jobs before migration")
    if source.execute(
        "SELECT 1 FROM plant_workflows WHERE json_extract(data,'$.incident.state')='investigating' LIMIT 1"
    ).fetchone():
        raise ValueError("Drain investigations before migration")
    if source.execute(
        "SELECT 1 FROM ai_usage WHERE json_extract(data,'$.status')='reserved' LIMIT 1"
    ).fetchone():
        raise ValueError("Settle provider reservations before migration")


def row_digest(rows):
    digest = hashlib.sha256()
    count = 0
    for row in rows:
        digest.update(json.dumps(tuple(row), ensure_ascii=False, allow_nan=False).encode())
        digest.update(b"\n")
        count += 1
    return {"count": count, "sha256": digest.hexdigest()}


def ordering(source, table, *, postgres=False):
    # Match SQLite binary ordering even when PostgreSQL uses a different database locale.
    collation = '"C"' if postgres else "BINARY"
    return ",".join(
        f'"{column[1]}"' + (f" COLLATE {collation}" if column[2] == "TEXT" else "")
        for column in source.execute(f'PRAGMA table_info("{table}")')
    )


def manifest(source):
    # Known schema names only; never interpolate names supplied by the source file.
    with closing(canonical()) as expected:
        tables = definitions(expected)
    return {
        name: row_digest(
            source.execute(
                f'SELECT *{",rowid" if name in ROWID_TABLES else ""} FROM "{name}" ORDER BY '
                + ordering(source, name)
            )
        )
        for name in sorted(tables)
    }


def import_snapshot(source, connection, schema="plantsense"):
    """Import once, or verify an exact retry. A mismatch rolls back all changes."""
    from psycopg import sql

    if not re.fullmatch(r"plantsense(?:_[a-z0-9_]+)?", schema):
        raise ValueError("Use a dedicated plantsense schema")
    validate_source(source)
    expected = manifest(source)
    sequences = dict(source.execute("SELECT name,seq FROM sqlite_sequence"))
    identity = hashlib.sha256(json.dumps([expected, sequences], sort_keys=True).encode()).hexdigest()
    with connection.transaction():
        connection.execute("SET LOCAL lock_timeout = '20s'")
        connection.execute("SELECT pg_advisory_xact_lock(735682901)")
        connection.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema)))
        connection.execute(sql.SQL("SET LOCAL search_path TO {}, pg_catalog").format(sql.Identifier(schema)))
        present = connection.execute(
            "SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname=%s", (schema,)
        ).fetchall()
        retry = bool(present)
        if retry:
            if {r[0] for r in present} != set(expected) | {"migration_import"}:
                raise ValueError("Target schema is not empty or is incompatible")
            receipt = connection.execute("SELECT source_hash FROM migration_import").fetchall()
            if receipt != [(identity,)]:
                raise ValueError("Target contains a different source snapshot")
        else:
            for statement in postgres_ddl():
                connection.execute(statement)
            connection.execute(Path(__file__).with_name("postgres-functions.sql").read_text())
            with closing(canonical()) as reviewed:
                tables = definitions(reviewed)
            for table in table_order(tables):
                query = sql.SQL("COPY {} FROM STDIN").format(sql.Identifier(table))
                with connection.cursor().copy(query) as writer:
                    for row in source.execute(
                        f'SELECT *{",rowid" if table in ROWID_TABLES else ""} FROM "{table}"'
                    ):
                        writer.write_row(row)
            for table in ("plant_audit", "issue_events", *sorted(ROWID_TABLES)):
                column = "rowid" if table in ROWID_TABLES else "sequence"
                connection.execute(
                    sql.SQL(
                        "SELECT setval(pg_get_serial_sequence(%s,%s), "
                        "GREATEST(COALESCE(MAX({column}),0),%s,1), "
                        "GREATEST(COALESCE(MAX({column}),0),%s)>0) FROM {table}"
                    ).format(table=sql.Identifier(table), column=sql.Identifier(column)),
                    (f"{schema}.{table}", column, sequences.get(table, 0), sequences.get(table, 0)),
                )
        for table, proof in expected.items():
            query = sql.SQL("SELECT * FROM {} ORDER BY " + ordering(source, table, postgres=True))
            with connection.cursor(name="verify_import") as cursor:
                cursor.execute(query.format(sql.Identifier(table)))
                if row_digest(cursor) != proof:
                    raise ValueError("Imported content does not match the snapshot")
        if not retry:
            connection.execute(
                "CREATE TABLE migration_import (source_hash TEXT PRIMARY KEY, "
                "verified_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)"
            )
            connection.execute("INSERT INTO migration_import(source_hash) VALUES (%s)", (identity,))
    return {"tables": len(expected), "rows": sum(p["count"] for p in expected.values()), "retry": retry}


def main():
    import psycopg

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--schema", default="plantsense")
    args = parser.parse_args()
    dsn = os.environ.get("PLANTSENSE_MIGRATION_DSN")
    if not dsn:
        parser.error("Set PLANTSENSE_MIGRATION_DSN outside the command line")
    try:
        with snapshot(args.source) as source, psycopg.connect(dsn, autocommit=True) as connection:
            print(json.dumps(import_snapshot(source, connection, args.schema)))
    except Exception as exc:
        # Driver errors can contain credentials, SQL values or private record contents.
        print(f"Migration failed ({type(exc).__name__}); transaction rolled back.", file=sys.stderr)
        raise SystemExit(1) from None


if __name__ == "__main__":
    main()
